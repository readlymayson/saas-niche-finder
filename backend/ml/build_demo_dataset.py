def build_rows(rng: random.Random) -> list[dict]:
    pain: list[dict] = []
    non: list[dict] = []
    for i, tmpl in enumerate(PAIN_SEEDS):
        for j in range(3):
            idx = i * 3 + j
            pain.append({"text": tmpl % idx, "label": 1})
    for i, tmpl in enumerate(NON_PAIN_SEEDS):
        for j in range(3):
            idx = i * 3 + j
            non.append({"text": tmpl % idx, "label": 0})
    if len(pain) != 150 or len(non) != 150:
        msg = (
            "Ожидалось по 150 строк на класс (50 шаблонов × 3 варианта). "
            f"Сейчас: «боль»={len(pain)} (шаблонов {len(PAIN_SEEDS)}), "
            f"«не боль»={len(non)} (шаблонов {len(NON_PAIN_SEEDS)})."
        )
        raise ValueError(msg)
    rows = pain + non
    rng.shuffle(rows)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description="Собрать train.jsonl (300 строк)")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent / "data" / "train.jsonl",
    )
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    rng = random.Random(args.seed)
    rows = build_rows(rng)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Записано {len(rows)} строк в {args.out}")


if __name__ == "__main__":
    main()
